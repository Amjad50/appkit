//! A small layer over axum: auto-registered routes with OpenAPI, layered config,
//! telemetry, background tasks and graceful shutdown. Plain axum keeps working inside it.

pub mod config;
mod error;
#[cfg(feature = "otel")]
mod otel;
mod security;
mod server;
mod state;
pub mod telemetry;

pub use appkit_macros::{delete, get, patch, post, put};
pub use error::{ApiError, ApiResult};
pub use security::Security;
pub use server::{Server, openapi};
pub use state::State;
pub use tokio_util::sync::CancellationToken;
pub use {axum, utoipa};

/// Everything a module with routes or API types needs: `use appkit::prelude::*;`.
///
/// It also brings the `utoipa` crate into scope, which the code generated by `#[derive(ToSchema)]`,
/// `#[derive(IntoParams)]` and the route macros refers to, so you do not depend on `utoipa`
/// (or `axum`) yourself.
pub mod prelude {
    pub use crate::{ApiError, ApiResult, CancellationToken, State, delete, get, patch, post, put};
    pub use axum::extract::{Extension, Form, Json, Multipart, Path, Query};
    pub use axum::http::StatusCode;
    pub use axum::response::{IntoResponse, Response};
    pub use utoipa::{self, IntoParams, ToSchema};
}

#[doc(hidden)]
pub use {inventory, utoipa_axum};

#[doc(hidden)]
pub mod __private {
    pub use crate::security::{Found, Probe, Secured, Unsecured, register};
}

/// One route registered by `#[get]`/`#[post]`/...; collected with `inventory`.
#[doc(hidden)]
pub struct Route {
    pub register: fn(utoipa_axum::router::OpenApiRouter) -> utoipa_axum::router::OpenApiRouter,
}
inventory::collect!(Route);

